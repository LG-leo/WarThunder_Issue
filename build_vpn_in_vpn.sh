#!/usr/bin/env bash
# ============================================================
# build_vpn_in_vpn.sh  (public / shareable version)
#
# Source: https://github.com/LG-leo/WarThunder_Issue/blob/main/build_vpn_in_vpn.sh
# Raw:    https://raw.githubusercontent.com/LG-leo/WarThunder_Issue/main/build_vpn_in_vpn.sh
# Guide:  https://github.com/LG-leo/WarThunder_Issue/blob/main/VPN_IN_VPN.md
#
#   WARP MASQUE (your own profile) -> Proton VPN Free -> Gaijin
#
# This version does NOT contain WARP MASQUE private keys.
# It assumes you already have a working WARP MASQUE profile in
# Clash Verge Rev (generated by usque / warp-masque-actions),
# and adds a Proton VPN Free WireGuard hop in front of it via
# Clash Verge's global Merge.
#
# RU:
#   Скрипт добавляет бесплатный Proton VPN (WireGuard) перед вашим
#   собственным профилем WARP MASQUE. Ключи WARP не передаются.
#   Для России: включите WARP/TUN, при необходимости используйте
#   --proxy http://127.0.0.1:7897 для входа в Proton API.
#
# Usage:
#   ./build_vpn_in_vpn.sh
#   ./build_vpn_in_vpn.sh --warp-group "🚀 节点选择"
#   ./build_vpn_in_vpn.sh --countries JP,US,NL --proxy http://127.0.0.1:7897
#   ./build_vpn_in_vpn.sh --conf /path/to/protonvpn.conf
#   ./build_vpn_in_vpn.sh --help
# ============================================================

set -euo pipefail

# Works both as ./build_vpn_in_vpn.sh and as:
#   curl -fsSL .../build_vpn_in_vpn.sh | bash
if [ -n "${BASH_SOURCE[0]:-}" ] && [ -f "${BASH_SOURCE[0]}" ]; then
  SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
else
  SCRIPT_DIR="${WT_CF_DIR:-$HOME/WT_CF}"
  mkdir -p "$SCRIPT_DIR"
fi

GEN="${GEN:-$SCRIPT_DIR/protonvpn-wg-confgen}"
CONF="${CONF:-$SCRIPT_DIR/protonvpn.conf}"
OUT="${OUT:-$SCRIPT_DIR/WT_CF_chain.merge.yaml}"
COUNTRIES="${COUNTRIES:-JP,US,NL}"
WARP_GROUP="${WARP_GROUP:-🚀 节点选择}"
PROXY="${PROXY:-}"
USERNAME="${USERNAME:-}"
SKIP_GEN=0

usage() {
  cat <<'EOF'
build_vpn_in_vpn.sh (public version)

  Adds Proton VPN Free before your existing WARP MASQUE profile.

Options:
  --warp-group NAME    existing WARP group used as first hop
                       (default: 🚀 节点选择; use ♻️ 自动选择 if that is yours)
  --countries LIST     Proton countries (default: JP,US,NL)
  --username USER      Proton username; otherwise prompts
  --proxy URL          proxy for Proton API/login, e.g. http://127.0.0.1:7897
  --conf FILE          use an existing Proton WireGuard .conf; skip generation
  --out FILE           output Merge file (default: ./WT_CF_chain.merge.yaml)
  --gen FILE           protonvpn-wg-confgen path
  -h, --help           show this help

After running:
  1. Open the generated .merge.yaml.
  2. Clash Verge Rev -> Profiles -> Global Merge (全局扩展配置) -> paste.
  3. Select your own WARP MASQUE profile; enable TUN.
  4. Proxy -> 🎮 WT-VPN -> Proton-Free.
EOF
}

while [ $# -gt 0 ]; do
  case "$1" in
    --warp-group) WARP_GROUP="${2:?}"; shift 2 ;;
    --countries) COUNTRIES="${2:?}"; shift 2 ;;
    --username) USERNAME="${2:?}"; shift 2 ;;
    --proxy) PROXY="${2:?}"; shift 2 ;;
    --conf) CONF="${2:?}"; SKIP_GEN=1; shift 2 ;;
    --out) OUT="${2:?}"; shift 2 ;;
    --gen) GEN="${2:?}"; shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "unknown option: $1" >&2; usage >&2; exit 2 ;;
  esac
done

say() { printf '%s\n' "$*"; }
die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }
need_cmd() { command -v "$1" >/dev/null 2>&1 || die "missing command: $1"; }

# Read a line from the terminal even when the script itself came from stdin
# (curl ... | bash).  Falls back to stdin if /dev/tty is unavailable.
ask() {
  local prompt="$1" value=""
  if [ -r /dev/tty ]; then
    read -r -p "$prompt" value < /dev/tty || true
  else
    read -r -p "$prompt" value || true
  fi
  printf '%s' "$value"
}

need_cmd python3
say "Working directory: $SCRIPT_DIR"

if [ -n "$PROXY" ]; then
  export HTTP_PROXY="$PROXY" HTTPS_PROXY="$PROXY"
  export http_proxy="$PROXY" https_proxy="$PROXY"
  say "Using proxy for Proton API: $PROXY"
fi

download_generator() {
  need_cmd curl
  need_cmd tar

  local os arch asset version tmp
  os="$(uname -s)"
  arch="$(uname -m)"
  version="0.17.3"

  case "$os/$arch" in
    Darwin/arm64) asset="protonvpn-wg-confgen_${version}_darwin_arm64.tar.gz" ;;
    Darwin/x86_64) asset="protonvpn-wg-confgen_${version}_darwin_amd64.tar.gz" ;;
    Linux/aarch64|Linux/arm64) asset="protonvpn-wg-confgen_${version}_linux_arm64.tar.gz" ;;
    Linux/x86_64|Linux/amd64) asset="protonvpn-wg-confgen_${version}_linux_amd64.tar.gz" ;;
    *) die "unsupported platform: $os/$arch" ;;
  esac

  tmp="$(mktemp -d)"
  say "Downloading $asset ..."
  curl -fsSL --retry 3 -o "$tmp/$asset" \
    "https://github.com/hatemosphere/protonvpn-wg-confgen/releases/download/v${version}/${asset}"
  curl -fsSL --retry 3 -o "$tmp/checksums.txt" \
    "https://github.com/hatemosphere/protonvpn-wg-confgen/releases/download/v${version}/checksums.txt"

  if command -v shasum >/dev/null 2>&1; then
    local sum expected
    sum="$(shasum -a 256 "$tmp/$asset" | awk '{print $1}')"
    expected="$(grep " ${asset}$" "$tmp/checksums.txt" | awk '{print $1}')"
    [ -n "$expected" ] || die "checksum entry not found for $asset"
    [ "$sum" = "$expected" ] || die "checksum mismatch for $asset"
  fi

  tar -xzf "$tmp/$asset" -C "$tmp"
  install -m 755 "$tmp/protonvpn-wg-confgen" "$GEN"
  rm -rf "$tmp"
  say "Installed: $GEN"
}

if [ "$SKIP_GEN" -eq 0 ]; then
  if [ ! -x "$GEN" ]; then
    download_generator
  fi

  if [ -z "$USERNAME" ]; then
    USERNAME="$(ask 'Proton VPN username (email): ')"
  fi
  [ -n "$USERNAME" ] || die "Proton username is required"

  say ""
  say "Generating Proton WireGuard config (password will be prompted)..."
  if [ -r /dev/tty ]; then
    "$GEN" \
      --username "$USERNAME" \
      --countries "$COUNTRIES" \
      --free-only \
      --p2p-only=false \
      --accelerator=false \
      --output "$CONF" < /dev/tty
  else
    "$GEN" \
      --username "$USERNAME" \
      --countries "$COUNTRIES" \
      --free-only \
      --p2p-only=false \
      --accelerator=false \
      --output "$CONF"
  fi
  say "Wrote: $CONF"
else
  [ -f "$CONF" ] || die "missing Proton config: $CONF"
  say "Using existing Proton config: $CONF"
fi

say ""
say "Building Clash Verge Merge snippet ..."
python3 - "$CONF" "$OUT" "$WARP_GROUP" <<'PY'
import json
import sys

conf_path, out_path, warp_group = sys.argv[1], sys.argv[2], sys.argv[3]

sections = {"Interface": {}, "Peer": {}}
current = None
with open(conf_path, "r", encoding="utf-8") as fh:
    for raw in fh:
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("[") and line.endswith("]"):
            current = line[1:-1].strip()
            sections.setdefault(current, {})
            continue
        if "=" not in line or current is None:
            continue
        key, value = line.split("=", 1)
        sections[current][key.strip().lower()] = value.strip()

iface = sections.get("Interface", {})
peer = sections.get("Peer", {})
private_key = iface.get("privatekey", "")
public_key = peer.get("publickey", "")
endpoint = peer.get("endpoint", "")
addresses = iface.get("address", "")
allowed = peer.get("allowedips", "0.0.0.0/0")
dns = iface.get("dns", "1.1.1.1")
mtu = iface.get("mtu", "1420")
keepalive = peer.get("persistentkeepalive", "25")

if not (private_key and public_key and endpoint and addresses):
    sys.exit("incomplete Proton config: need PrivateKey, Address, PublicKey, Endpoint")

ip = None
for item in addresses.split(","):
    host = item.strip().split("/", 1)[0]
    if ":" not in host and host:
        ip = host
        break
if not ip:
    sys.exit("no IPv4 Address found; regenerate Proton config without --ipv6")

if endpoint.startswith("["):
    host, port = endpoint[1:].split("]:", 1)
else:
    host, port = endpoint.rsplit(":", 1)

allowed_list = [x.strip() for x in allowed.split(",") if x.strip() and ":" not in x] or ["0.0.0.0/0"]
dns_list = [x.strip() for x in dns.split(",") if x.strip() and ":" not in x]
dns_value = dns_list[0] if dns_list else "1.1.1.1"

def q(value):
    return json.dumps(str(value), ensure_ascii=False)

lines = [
    "# Generated by build_vpn_in_vpn.sh",
    "# Paste into Clash Verge Rev -> Profiles -> Global Merge (全局扩展配置).",
    "# It uses your existing WARP group as the first hop; no WARP keys are included.",
    "# First hop: " + warp_group,
    "prepend-proxies:",
    "  - name: Proton-Free",
    "    type: wireguard",
    "    server: " + q(host),
    "    port: " + str(port),
    "    ip: " + q(ip),
    "    private-key: " + q(private_key),
    "    public-key: " + q(public_key),
    "    allowed-ips:",
    *["      - " + q(item) for item in allowed_list],
    "    udp: true",
    "    mtu: " + str(mtu),
    "    persistent-keepalive: " + str(keepalive),
    "    dialer-proxy: " + q(warp_group),
    "    remote-dns-resolve: true",
    "    dns:",
    "      - " + q(dns_value),
    "prepend-proxy-groups:",
    '  - name: "🎮 WT-VPN"',
    "    type: select",
    "    proxies:",
    "      - Proton-Free",
    "      - " + q(warp_group),
    "      - DIRECT",
    "prepend-rules:",
    '  - "DST-PORT,20010,🎮 WT-VPN"',
    '  - "DST-PORT,20011,🎮 WT-VPN"',
    "",
]
with open(out_path, "w", encoding="utf-8") as fh:
    fh.write("\n".join(lines))
print(f"wrote {out_path} (Merge snippet)")
print(f"  proton endpoint : {host}:{port}")
print(f"  proton ip       : {ip}")
print(f"  first hop       : {warp_group}")
PY

say ""
say "Done: $OUT"
say ""
say "Next:"
say "  1. Open $OUT and copy everything."
say "  2. Clash Verge Rev -> Profiles -> Global Merge (全局扩展配置) -> paste -> save."
say "  3. Select your own WARP MASQUE profile; enable TUN."
say "  4. Proxy -> 🎮 WT-VPN -> Proton-Free."
say ""
say "If your WARP profile does not have '$WARP_GROUP', rerun with:"
say "  --warp-group \"the group name in your WARP profile\""
say ""
say "Note: Global Merge applies to every profile while it is enabled."
